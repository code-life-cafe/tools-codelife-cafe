// PR進行照合の純粋評価。取得（scripts/pr-gate-status.mjs）とは分離し、副作用を持たない。
// 出力はMerge許可ではなく「いま何を待つか/何をすべきか」の判定。Merge操作は含まない。
// 取得失敗・未知形式・旧SHAは合格にせず、必ず待ちかblockedに倒す（fail-closed）。

export const STATES = [
	'ready',
	'sync-base',
	'wait-ci',
	'wait-review',
	'wait-classification',
	'blocked',
	'merge-ready',
	'wait-deploy',
	'verify-production',
	'close',
	'done',
];

export const CODEX_BOT_LOGIN = 'chatgpt-codex-connector[bot]';
// 独立分類を受け付ける発信者。Codexチャットの投稿はユーザー権限で行われるため
// ログインだけでは人間と区別できない。Claude Code自身の投稿（フッター付き）は除外する。
export const CLASSIFICATION_AUTHORS = ['maru0014', CODEX_BOT_LOGIN];
export const REQUIRED_CHECKS = ['lint', 'e2e'];
export const MAX_FIX_LOOPS = 3;

const FULL_SHA = /^[0-9a-f]{40}$/;
const CLAUDE_FOOTER = /Generated by \[Claude Code\]/;

/** @returns {any} */
const result = (state, /** @type {any} */ extra = {}) => ({
	state,
	waitingOn: null,
	retriable: false,
	reasons: [],
	suggest: null,
	...extra,
});

function parseJsonMarker(body, name) {
	const m = new RegExp(`<!--\\s*${name}\\s+(\\{.*?\\})\\s*-->`, 's').exec(
		body ?? '',
	);
	if (!m) return null;
	try {
		return JSON.parse(m[1]);
	} catch {
		return null;
	}
}

// Codex Review Summary（bot本人のコメント）を読み、対象headの完了状況を返す。
export function readCodexSummary(comments, { repo, number, headSha }) {
	const botComments = comments
		.filter((c) => c.login === CODEX_BOT_LOGIN)
		.filter((c) => /codex-review-state:v1/.test(c.body ?? ''))
		.sort(
			(a, b) =>
				Date.parse(b.updatedAt ?? b.createdAt) -
				Date.parse(a.updatedAt ?? a.createdAt),
		);
	const latest = botComments[0];
	if (!latest)
		return {
			ok: false,
			code: 'summary-missing',
			detail: 'Codex Review Summaryが未取得',
		};
	const state = parseJsonMarker(latest.body, 'codex-review-state:v1');
	const sec = parseJsonMarker(latest.body, 'codex-security-review:v1');
	if (!state || !sec)
		return {
			ok: false,
			code: 'summary-unparsable',
			detail: 'メタデータ形式が未知',
		};
	if (sec.repository !== repo || sec.pullRequestNumber !== number) {
		return {
			ok: false,
			code: 'summary-other-pr',
			detail: 'repository/PR番号が不一致',
		};
	}
	const code = state.code_review ?? {};
	const security = state.security_review ?? {};
	// 完全SHAのみ比較する。欠落（Code対象SHAなし等）は合格にしない。
	const check = (label, r) => {
		if (!FULL_SHA.test(r.commit_sha ?? '')) {
			return {
				code: `${label}-sha-missing`,
				detail: `${label}の対象commit_shaが欠落/不正`,
			};
		}
		if (r.commit_sha !== headSha) {
			return {
				code: `${label}-stale`,
				detail: `${label}は旧head ${r.commit_sha.slice(0, 7)}`,
			};
		}
		if (r.status !== 'completed') {
			return {
				code: `${label}-running`,
				detail: `${label}のstatus=${r.status}`,
			};
		}
		if (r.has_unresolved_findings !== false) {
			return {
				code: `${label}-findings`,
				detail: `${label}に未解決指摘あり/不明`,
			};
		}
		return null;
	};
	if (sec.headSha !== headSha || sec.status !== 'completed') {
		const stale = sec.headSha !== headSha;
		return {
			ok: false,
			code: stale ? 'security-meta-stale' : 'security-meta-running',
			detail: `security-review meta headSha=${String(sec.headSha).slice(0, 7)} status=${sec.status}`,
		};
	}
	const problems = [check('code', code), check('security', security)].filter(
		Boolean,
	);
	if (problems.length) return { ok: false, ...problems[0], all: problems };
	return { ok: true };
}

// 独立分類の証拠。同一headの完全SHAと分類を含み、許可された発信者で、Claude自身の投稿ではないもの。
export function findClassification(comments, headSha) {
	const hits = [];
	for (const c of comments) {
		if (!CLASSIFICATION_AUTHORS.includes(c.login)) continue;
		if (CLAUDE_FOOTER.test(c.body ?? '')) continue;
		const marker = parseJsonMarker(c.body, 'codex-classification:v1');
		if (marker) {
			if (
				marker.headSha === headSha &&
				['A', 'B', 'C'].includes(marker.class)
			) {
				hits.push({
					id: c.id,
					class: marker.class,
					risk: marker.risk ?? null,
					form: 'marker',
					at: c.createdAt,
				});
			}
			continue;
		}
		if (!(c.body ?? '').includes(headSha)) continue;
		const m = /独立分類[:：]\s*\**\s*(承認済み)?([ABC])\b/.exec(c.body ?? '');
		if (m)
			hits.push({
				id: c.id,
				class: m[2],
				approved: Boolean(m[1]),
				form: 'text',
				at: c.createdAt,
			});
	}
	hits.sort((a, b) => Date.parse(b.at) - Date.parse(a.at));
	return hits;
}

// 修正周回。履歴（コメント/本文）の最大値を採用し、再起動や重複で0に戻さない。取れなければnull。
export function readFixLoops(texts) {
	let max = null;
	for (const t of texts) {
		for (const m of (t ?? '').matchAll(/修正ループ[:：]\s*(\d+)\s*\/\s*3/g)) {
			max = Math.max(max ?? 0, Number(m[1]));
		}
	}
	return max;
}

function summarizeChecks(checks, headSha) {
	const byName = new Map();
	for (const c of checks) {
		if (c.headSha !== headSha) continue; // 旧SHAの結果は無視
		const prev = byName.get(c.name);
		if (
			!prev ||
			Date.parse(c.startedAt ?? 0) >= Date.parse(prev.startedAt ?? 0)
		)
			byName.set(c.name, c);
	}
	const missing = [];
	const pending = [];
	const failed = [];
	for (const name of REQUIRED_CHECKS) {
		const c = byName.get(name);
		if (!c) missing.push(name);
		else if (c.status !== 'completed') pending.push(name);
		else if (c.conclusion !== 'success') failed.push(`${name}:${c.conclusion}`);
	}
	return { missing, pending, failed };
}

// snapshot: scripts/pr-gate-status.mjs が正規化して渡す。unknown/null は「不明」として扱う。
/** @param {any} snapshot @returns {any} */
export function evaluate(snapshot) {
	const { pr, repo, errors = [] } = snapshot;
	if (!pr || !FULL_SHA.test(pr.headSha ?? '')) {
		return result('blocked', {
			retriable: true,
			reasons: ['PR/headを取得できない', ...errors],
		});
	}
	const comments = snapshot.comments ?? null;
	const head = pr.headSha;
	const base = { head, base: pr.baseSha ?? null };

	if (pr.merged) return evaluatePostMerge(snapshot, base);
	if (pr.state !== 'open')
		return result('done', { ...base, reasons: ['マージされずに閉じている'] });

	if (comments === null) {
		return result('blocked', {
			...base,
			retriable: true,
			reasons: ['コメント取得失敗', ...errors],
		});
	}
	if (snapshot.checks == null) {
		return result('blocked', {
			...base,
			retriable: true,
			reasons: ['check-run取得失敗', ...errors],
		});
	}

	const ci = summarizeChecks(snapshot.checks, head);
	if (ci.failed.length) {
		return result('blocked', {
			...base,
			reasons: [`必須CI失敗: ${ci.failed.join(', ')}`],
			suggest: 'fix-ci(修正周回に計上)',
		});
	}
	if (pr.mergeableState === 'dirty') {
		return result('blocked', {
			...base,
			reasons: ['競合あり。意味判断が必要なら人間へ'],
			suggest: 'merge-base-and-resolve',
		});
	}
	// 最新baseを含まないheadは新headでCI/レビューをやり直すため、待つ前にbase取り込みを優先する。
	if (snapshot.behindBy == null) {
		return result('blocked', {
			...base,
			retriable: true,
			reasons: ['base差分(behind_by)を取得できない', ...errors],
		});
	}
	if (snapshot.behindBy > 0) {
		return result('sync-base', {
			...base,
			reasons: [`headはbaseに${snapshot.behindBy}コミット遅れ`],
			suggest: 'merge-main-then-push(CI/レビュー再照合)',
		});
	}
	if (ci.pending.length || ci.missing.length) {
		const reasons = [
			...ci.pending.map((n) => `${n}実行中`),
			...ci.missing.map((n) => `${n}未起動(対象head)`),
		];
		return result('wait-ci', {
			...base,
			waitingOn: 'CI',
			retriable: true,
			reasons,
		});
	}
	if (pr.draft) {
		return result('ready', {
			...base,
			reasons: ['対象headの必須CIが成功したDraft'],
			suggest: 'mark-ready-for-review(二重のreview依頼はしない)',
		});
	}

	const loops = readFixLoops([pr.body, ...comments.map((c) => c.body)]);
	if (loops != null && loops > MAX_FIX_LOOPS) {
		return result('blocked', {
			...base,
			reasons: [`修正ループ${loops}/3超過`],
			suggest: 'return-to-human',
		});
	}

	const review = readCodexSummary(comments, {
		repo,
		number: pr.number,
		headSha: head,
	});
	if (!review.ok) {
		const blockingFindings = /findings$/.test(review.code);
		if (blockingFindings) {
			return result('blocked', {
				...base,
				reasons: [review.detail],
				suggest: 'classify-and-fix-findings',
			});
		}
		const sha = /sha-missing$/.test(review.code);
		return result('wait-review', {
			...base,
			waitingOn: 'Codexレビュー',
			retriable: true,
			reasons: [review.detail],
			suggest:
				sha || review.code === 'summary-missing'
					? 'request-review-once-if-not-requested-for-this-head'
					: null,
		});
	}

	const classes = findClassification(comments, head);
	if (!classes.length) {
		return result('wait-classification', {
			...base,
			waitingOn: '独立分類(同一head)',
			retriable: true,
			reasons: [
				'対象headの完全SHAを含む独立分類が未記録。「重大指摘なし」では代替しない',
			],
			suggest: 'request-independent-classification',
		});
	}
	const classSet = new Set(classes.map((c) => c.class));
	const klass = ['C', 'B', 'A'].find((k) => classSet.has(k)); // 矛盾時は厳しい側
	if (klass !== 'A') {
		return result('blocked', {
			...base,
			classification: klass,
			reasons: [`分類${klass}: 承認原文・承認範囲の確認が必要(自動判定しない)`],
			suggest: 'verify-approval-reference-then-human-if-unapproved',
		});
	}

	if (snapshot.unresolvedThreads == null) {
		return result('blocked', {
			...base,
			retriable: true,
			reasons: ['未解決thread数を取得できない(GraphQL/認証)'],
		});
	}
	if (snapshot.unresolvedThreads > 0) {
		return result('blocked', {
			...base,
			reasons: [`未解決thread ${snapshot.unresolvedThreads}件`],
			suggest: 'respond-to-threads',
		});
	}
	if (
		snapshot.rules?.strict !== true ||
		!REQUIRED_CHECKS.every((n) => snapshot.rules.requiredChecks?.includes(n))
	) {
		return result('blocked', {
			...base,
			retriable: snapshot.rules == null,
			reasons: ['strict required checks(lint/e2e)を確認できない/無効'],
		});
	}
	if (loops == null) {
		return result('blocked', {
			...base,
			retriable: true,
			reasons: ['修正ループ履歴を確認できない'],
		});
	}
	if (pr.mergeableState !== 'clean') {
		return result('wait-ci', {
			...base,
			waitingOn: 'mergeable状態',
			retriable: true,
			reasons: [`mergeable_state=${pr.mergeableState}`],
		});
	}
	return result('merge-ready', {
		...base,
		classification: 'A',
		reasons: [
			'全条件成立。Merge直前に再取得し、head指定の通常Mergeを既存主体が行う',
		],
		suggest: `merge --match-head-commit ${head}`,
	});
}

function evaluatePostMerge(snapshot, base) {
	const { pr, comments = [], deploy, issue } = snapshot;
	const sha = pr.mergeCommitSha;
	if (!FULL_SHA.test(sha ?? '')) {
		return result('blocked', {
			...base,
			retriable: true,
			reasons: ['merge commit SHAを取得できない'],
		});
	}
	const run = (deploy?.runs ?? []).find((r) => r.headSha === sha);
	if (!run) {
		return result('wait-deploy', {
			...base,
			mergeCommit: sha,
			waitingOn: 'Deploy起動',
			retriable: true,
			reasons: ['merge commitのDeploy runが未確認'],
		});
	}
	if (run.status !== 'completed') {
		return result('wait-deploy', {
			...base,
			mergeCommit: sha,
			waitingOn: 'Deploy',
			retriable: true,
			reasons: [`deploy status=${run.status}`],
		});
	}
	if (run.conclusion !== 'success') {
		return result('blocked', {
			...base,
			mergeCommit: sha,
			reasons: [`Deploy ${run.conclusion}。公開確認失敗として人間へ通知`],
		});
	}
	const verified = comments.some(
		(c) =>
			(c.body ?? '').includes(sha) &&
			/公開(SHA|確認)/.test(c.body ?? '') &&
			/(HTTP|http)\s*200|status\s*200/.test(c.body ?? ''),
	);
	if (!verified) {
		return result('verify-production', {
			...base,
			mergeCommit: sha,
			reasons: ['Deploy成功。公開SHA/HTTP/必要動作の確認記録が未投稿'],
			suggest: 'record-production-verification',
		});
	}
	if (issue?.state === 'open') {
		return result('close', {
			...base,
			mergeCommit: sha,
			reasons: [
				'公開確認記録あり。対象Issueが未closeで、RUM待ちはNotionへ引継ぎ',
			],
			suggest: 'close-issue-and-handoff-rum-to-notion',
		});
	}
	return result('done', {
		...base,
		mergeCommit: sha,
		reasons: ['公開確認済み・Issue close済み'],
	});
}
